#!/usr/bin/env node
/**
 * Freezes the 50-level campaign.
 *
 *   npm run campaign
 *
 * 1. hand-made levels are taken as-is,
 * 2. every other id comes from the seeded generator (bot-verified, 0 penalties),
 * 3. par time is computed for every level by the autoplay bot,
 * 4. result → src/content/campaign.data.ts (+ levels/campaign.json for tools / Supabase seed).
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { autoplay, computePar, loadLevel, validateLevel } from '../dist/core/index.js';
import { HANDMADE } from '../dist/content/handmade.js';
import { CURRICULUM, buildGeneratedLevel } from '../dist/content/generator.js';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const TOTAL = 50;
const t0 = Date.now();
const levels = [];
const report = [];

for (let id = 1; id <= TOTAL; id++) {
  let def = HANDMADE.find((l) => l.id === id);
  let source = 'hand';
  let seed = null;
  if (!def) {
    const spec = CURRICULUM.find((s) => s.id === id);
    if (!spec) throw new Error(`Level ${id}: na qo'lda, na generator spetsifikatsiyasi bor`);
    const cand = buildGeneratedLevel(spec);
    def = cand.def;
    source = 'gen';
    seed = cand.seed;
  }
  const v = validateLevel(def);
  if (!v.ok) throw new Error(`Level ${id} invalid:\n${v.errors.join('\n')}`);
  const level = loadLevel(def);
  const bot = autoplay(level, { reactionTicks: 12 });
  if (!bot.completed || bot.penalties > 0) throw new Error(`Level ${id}: bot failed (completed=${bot.completed}, penalties=${bot.penalties})`);
  const parMs = computePar(level);
  const vehicles = level.spawns.length;
  levels.push({ ...def, parMs });
  report.push({ id, source, seed, band: def.band, junction: def.junction, vehicles, botS: +(bot.ticks / 60).toFixed(1), parS: parMs / 1000 });
}

const header = '// AUTO-GENERATED by scripts/build-campaign.mjs — do not edit by hand.\n' +
  '// Re-generate with: npm run campaign\n' +
  "import type { LevelDef } from '../core/types.js';\n\n";
writeFileSync(resolve(root, 'src/content/campaign.data.ts'), `${header}export const CAMPAIGN_DATA: readonly LevelDef[] = ${JSON.stringify(levels, null, 2)};\n`);
mkdirSync(resolve(root, 'levels'), { recursive: true });
writeFileSync(resolve(root, 'levels/campaign.json'), JSON.stringify(levels, null, 2) + '\n');

console.table(report);
const totalVehicles = report.reduce((s, r) => s + r.vehicles, 0);
console.log(`\n${levels.length} levels, ${totalVehicles} vehicles, built in ${((Date.now() - t0) / 1000).toFixed(1)} s`);
